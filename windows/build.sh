#!/usr/bin/env bash
# Builds ZIGMon Notifier for Windows (x64) - works on Linux, macOS or Windows (Git Bash)
# with the .NET 10 SDK:
#   1. writes ZigmonNotifier.Core/ReleaseKeys.cs from ../deploy/release-keys/*.pub
#      (the keys updates must be signed with; a test checks the two agree),
#   2. runs the tests of the core (protocol, TLS pinning, Ed25519, the updater, ...),
#   3. draws the app icon (Assets/app.ico) from the same painter the tray icon uses,
#   4. publishes one framework-dependent single-file ZigmonNotifier.exe (needs the
#      .NET 10 Desktop Runtime on Windows; the exe offers Microsoft's download if it is missing),
#   5. copies it to dist/ZigmonNotifier.exe and writes dist/notifier.json (the manifest
#      tools/make-release.sh signs into dist/notifier.json.sig - not made here),
#   6. zips exe + README to out/ZigmonNotifier-<version>-win-x64.zip.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
cd "$here"
version="$(sed -n 's:.*<Version>\(.*\)</Version>.*:\1:p' Directory.Build.props | head -n1)"
[ -n "$version" ] || { echo "no <Version> in Directory.Build.props" >&2; exit 1; }
grep -q "public const string Version = \"$version\";" ZigmonNotifier.Core/AppInfo.cs \
  || { echo "AppInfo.Version is not $version" >&2; exit 1; }
out="$here/out"
pub="$out/publish"
dist="$here/dist"
zip="$out/ZigmonNotifier-$version-win-x64.zip"

export DOTNET_CLI_TELEMETRY_OPTOUT=1
export DOTNET_NOLOGO=1
export SOURCE_DATE_EPOCH=0

echo "== release keys"
keys="$here/../deploy/release-keys"
gen="ZigmonNotifier.Core/ReleaseKeys.cs"
{
  cat <<'HEAD'
// <auto-generated>
// Written by windows/build.sh from deploy/release-keys/*.pub - do not edit by hand.
// The raw 32-byte Ed25519 public keys ZIGMon's releases are signed with; an update
// of the app is installed only when its manifest is signed by one of them.
// ReleaseKeyTests re-reads the folder and checks this file matches it.
// </auto-generated>
namespace ZigmonNotifier.Core;

public static partial class ReleaseKeys
{
    private static readonly (string Name, string Hex)[] EmbeddedHex =
    {
HEAD
  n=0
  for k in $(LC_ALL=C ls "$keys"/*.pub); do
    der_hex="$(grep -v -- '-----' "$k" | tr -d ' \r\n' | base64 -d | od -An -v -tx1 | tr -d ' \n')"
    case "$der_hex" in
      302a300506032b6570032100*) ;;
      *) echo "$k is not an Ed25519 public key" >&2; exit 1 ;;
    esac
    raw="${der_hex:24}"
    [ "${#raw}" -eq 64 ] || { echo "$k: not 32 key bytes" >&2; exit 1; }
    printf '        ("%s", "%s"),\n' "$(basename "$k" .pub)" "$raw"
    n=$((n + 1))
  done
  [ "$n" -gt 0 ] || { echo "no release keys in $keys" >&2; exit 1; }
  cat <<'TAIL'
    };
}
TAIL
} > "$gen.tmp"
mv "$gen.tmp" "$gen"

echo "== tests"
dotnet test ZigmonNotifier.Tests/ZigmonNotifier.Tests.csproj -c Release --nologo

echo "== icon"
dotnet run --project tools/IconGen/IconGen.csproj -c Release -- ZigmonNotifier/Assets/app.ico

echo "== publish"
rm -rf "$pub"
dotnet publish ZigmonNotifier/ZigmonNotifier.csproj -c Release -r win-x64 \
  --no-self-contained \
  -p:SelfContained=false \
  -p:EnableWindowsTargeting=true \
  -p:PublishSingleFile=true \
  -p:DebugType=none \
  -p:Deterministic=true \
  -p:ContinuousIntegrationBuild=true \
  -p:PathMap="$here=/zigmon/windows" \
  -p:Version="$version" \
  -o "$pub" --nologo

exe="$pub/ZigmonNotifier.exe"
[ -f "$exe" ] || { echo "no exe produced" >&2; exit 1; }

echo "== dist"
mkdir -p "$dist"
cp "$exe" "$dist/ZigmonNotifier.exe"
size="$(wc -c < "$dist/ZigmonNotifier.exe" | tr -d ' ')"
if command -v sha256sum >/dev/null 2>&1; then
  sha="$(sha256sum "$dist/ZigmonNotifier.exe" | cut -d' ' -f1)"
else
  sha="$(shasum -a 256 "$dist/ZigmonNotifier.exe" | cut -d' ' -f1)"
fi
# one line, these keys in this order, LF at the end: these exact bytes are what gets signed
printf '{"product":"ZIGMon Notifier","file":"ZigmonNotifier.exe","version":"%s","size":%s,"sha256":"%s","runtime":"Microsoft.WindowsDesktop.App 10.0"}\n' \
  "$version" "$size" "$sha" > "$dist/notifier.json"
# an old signature belongs to other bytes: make-release.sh signs again
if [ -f "$dist/notifier.json.sig" ]; then
  echo "note: dist/notifier.json.sig is from an earlier build - tools/make-release.sh signs the new notifier.json"
fi

echo "== zip"
rm -f "$zip"
stage="$out/stage"
rm -rf "$stage"
mkdir -p "$stage"
cp "$exe" "$stage/"
cp README.md "$stage/README.md"
cp NAVOD.md "$stage/NAVOD.md"
if command -v zip >/dev/null 2>&1; then
  (cd "$stage" && zip -q -X -9 "$zip" ZigmonNotifier.exe README.md NAVOD.md)
else
  python3 - "$stage" "$zip" <<'PY'
import sys, zipfile, os
stage, dest = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for name in ("ZigmonNotifier.exe", "README.md", "NAVOD.md"):
        info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        with open(os.path.join(stage, name), "rb") as f:
            z.writestr(info, f.read())
PY
fi
rm -rf "$stage"

echo
echo "exe:  $dist/ZigmonNotifier.exe ($size bytes)"
echo "json: $(cat "$dist/notifier.json")"
echo "zip:  $zip"
