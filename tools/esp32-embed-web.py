#!/usr/bin/env python3
"""Builds esp32/ZigmonGateway/web_assets.h from the readable web UI sources in
esp32/ZigmonGateway/web/: light, safe minification, gzip (level 9, reproducible), and C arrays
the firmware serves with Content-Encoding: gzip.

    python3 tools/esp32-embed-web.py            # writes the header
    python3 tools/esp32-embed-web.py --check    # exits 1 if the header is out of date

index.html refers to app.css / app.js with ?v=<hash of their content>, so the browser may cache
those for good and still picks up a new firmware's files at once.
"""
import gzip
import hashlib
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / 'esp32' / 'ZigmonGateway' / 'web'
OUT = ROOT / 'esp32' / 'ZigmonGateway' / 'web_assets.h'

TYPES = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
         '.js': 'application/javascript; charset=utf-8', '.svg': 'image/svg+xml'}


def min_css(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'\s+', ' ', s)
    s = re.sub(r'\s*([{};,>])\s*', r'\1', s)
    s = s.replace(';}', '}')
    return s.strip()


def min_js(s):
    # Conservative: drop whole-line // comments and blank lines, trim indentation. Nothing
    # inside a line is touched, so strings and regular expressions stay intact.
    out = []
    for line in s.splitlines():
        t = line.strip()
        if not t or t.startswith('//'):
            continue
        out.append(t)
    return '\n'.join(out) + '\n'


def min_html(s):
    s = re.sub(r'<!--.*?-->', '', s, flags=re.S)
    s = re.sub(r'>\s+<', '><', s)
    return s.strip()


def gz(data):
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9, mtime=0, filename='') as f:
        f.write(data)
    return buf.getvalue()


def build():
    files = {}
    for p in sorted(WEB.iterdir()):
        if p.suffix not in TYPES:
            continue
        text = p.read_text(encoding='utf-8')
        if p.suffix == '.css':
            text = min_css(text)
        elif p.suffix == '.js':
            text = min_js(text)
        elif p.suffix == '.svg':
            text = re.sub(r'>\s+<', '><', text).strip()
        files[p.name] = text
    if 'index.html' not in files:
        sys.exit('web/index.html is missing')
    html = files['index.html']
    for name in ('app.css', 'app.js'):
        h = hashlib.sha256(files[name].encode()).hexdigest()[:10]
        html = html.replace('"/%s"' % name, '"/%s?v=%s"' % (name, h))
    files['index.html'] = min_html(html)

    lines = ['// GENERATED by tools/esp32-embed-web.py from esp32/ZigmonGateway/web/ - do not edit.',
             '// The readable sources are in web/; run the script after changing them.',
             '#pragma once', '', '#include <stddef.h>', '#include <stdint.h>', '',
             '#ifndef PROGMEM', '#define PROGMEM', '#endif', '',
             'struct WebAsset {', '  const char* path;', '  const char* type;', '  const uint8_t* data;',
             '  size_t len;', '};', '']
    table = []
    total = 0
    for i, (name, text) in enumerate(sorted(files.items())):
        data = gz(text.encode('utf-8'))
        total += len(data)
        var = 'WEB_ASSET_%d' % i
        lines.append('// /%s: %d bytes, %d gzipped' % (name, len(text.encode()), len(data)))
        lines.append('static const uint8_t %s[] PROGMEM = {' % var)
        for j in range(0, len(data), 20):
            lines.append('  ' + ', '.join('0x%02x' % b for b in data[j:j + 20]) + ',')
        lines.append('};')
        lines.append('')
        table.append('  {"/%s", "%s", %s, sizeof(%s)},' % (name, TYPES[Path(name).suffix], var, var))
    lines.append('static const WebAsset WEB_ASSETS[] = {')
    lines += table
    lines.append('};')
    lines.append('static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);')
    lines.append('// total %d bytes in flash' % total)
    return '\n'.join(lines) + '\n', total


def main():
    text, total = build()
    if '--check' in sys.argv:
        cur = OUT.read_text() if OUT.exists() else ''
        if cur != text:
            print('web_assets.h is out of date: run tools/esp32-embed-web.py')
            return 1
        print('web_assets.h is up to date (%d bytes gzipped)' % total)
        return 0
    OUT.write_text(text)
    print('wrote %s (%d bytes gzipped)' % (OUT.relative_to(ROOT), total))
    return 0


if __name__ == '__main__':
    sys.exit(main())
