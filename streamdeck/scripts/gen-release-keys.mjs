// Writes src/core/release-keys.generated.ts from ../deploy/release-keys/*.pub, like
// windows/build.sh does for the notifier: the raw 32-byte Ed25519 public keys an update
// of the plugin must be signed with. test/release-keys.test.ts re-reads the folder.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "..", "deploy", "release-keys");
const out = join(here, "..", "src", "core", "release-keys.generated.ts");
const PREFIX = "302a300506032b6570032100";

export function readKeys(folder = dir) {
  const names = readdirSync(folder).filter((f) => f.endsWith(".pub")).sort();
  if (names.length === 0) throw new Error("no release keys in " + folder);
  return names.map((f) => {
    const pem = readFileSync(join(folder, f), "utf8");
    const der = Buffer.from(pem.split(/\r?\n/).filter((l) => l && !l.startsWith("-----")).join(""), "base64").toString("hex");
    if (!der.startsWith(PREFIX) || der.length !== PREFIX.length + 64) throw new Error(f + " is not an Ed25519 public key");
    return { name: f.slice(0, -4), hex: der.slice(PREFIX.length) };
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const keys = readKeys();
  const body = [
    "// <auto-generated>",
    "// Written by streamdeck/scripts/gen-release-keys.mjs from deploy/release-keys/*.pub - do not edit by hand.",
    "// The raw 32-byte Ed25519 public keys ZIGMon's releases are signed with; an update of the",
    "// plugin is installed only when its manifest is signed by one of them.",
    "// test/release-keys.test.ts re-reads the folder and checks this file matches it.",
    "// </auto-generated>",
    "export const RELEASE_KEYS: ReadonlyArray<{ readonly name: string; readonly hex: string }> = [",
    ...keys.map((k) => `  { name: ${JSON.stringify(k.name)}, hex: ${JSON.stringify(k.hex)} },`),
    "];",
    "",
  ].join("\n");
  writeFileSync(out, body);
  console.log("release keys: " + keys.map((k) => k.name).join(", "));
}
